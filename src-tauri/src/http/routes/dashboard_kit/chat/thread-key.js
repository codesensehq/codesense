// A thread's key, as the engine keys it (ThreadKey::new): the saved agent is the id before `@` (a new revision continues its threads), and no story is '', whose sessions are
// the ones the roster lists. The one rule for the bridge, the chat overlay and the pages.
export const threadOf=(agent,story)=>({agentId:String(agent||'').split('@')[0].trim(),storyId:String(story||'').trim()});
