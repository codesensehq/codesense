// Bundles the chat modules (dashboard_kit/chat/*.js, ES modules) into the one classic script a live doc loads,
// dashboard_kit/chat.js, which defines window.codesense.kit.chat. The modules are the source: chat-core.js is also served
// and imported as it is (DOM-free), and the context repo's story-view keeps a generated copy of the module folder.
//   node scripts/gen-dashboard-kit-chat.mjs          rewrite chat.js
//   node scripts/gen-dashboard-kit-chat.mjs --check  fail if chat.js is stale
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { buildSync } from "esbuild";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const KIT_DIR = join(ROOT, "src-tauri/src/http/routes/dashboard_kit");
export const CHAT_JS = join(KIT_DIR, "chat.js");
const BANNER =
  "// SPDX-License-Identifier: MIT\n// Generated by scripts/gen-dashboard-kit-chat.mjs from dashboard_kit/chat/*.js. Do not edit.\n";

export function bundleChat() {
  const result = buildSync({
    entryPoints: [join(KIT_DIR, "chat/index.js")],
    bundle: true,
    write: false,
    format: "iife",
    target: "es2020",
    legalComments: "none",
    charset: "utf8",
  });
  return BANNER + result.outputFiles[0].text;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const fresh = bundleChat();
  if (process.argv.includes("--check")) {
    if (readFileSync(CHAT_JS, "utf8") !== fresh) {
      console.error("dashboard_kit/chat.js is stale; run node scripts/gen-dashboard-kit-chat.mjs");
      process.exit(1);
    }
  } else {
    writeFileSync(CHAT_JS, fresh);
    console.log("Wrote dashboard_kit/chat.js");
  }
}
